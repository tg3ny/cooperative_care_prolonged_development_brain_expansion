if __name__=='__main__':
    parser = argparse.ArgumentParser(
        description='Regenerate Figures 3, 4, and Figure 3—figure supplement 1.'
    )
    parser.add_argument('--data-dir', default='.',
                        help='Directory containing the repository data files (default: repository root)')
    parser.add_argument('--output-dir', default='figures/generated',
                        help='Directory for generated PDF figures')
    args = parser.parse_args()
    data_dir = Path(args.data_dir)
    out = args.output_dir
    print("Generating final figures...")
    figure3_exp2(out, (
        data_dir / 'experiment2_control_trajectories.csv.gz',
        data_dir / 'experiment2_treatment_trajectories.csv.gz',
    ))
    figure4_exp3(out, data_dir / 'Data_S7_Mixed_Summary.csv')
    figureS6(out, (
        data_dir / 'gradual_ceiling_control_trajectories.csv.gz',
        data_dir / 'gradual_ceiling_treatment_trajectories.csv.gz',
    ))
    print("Done.")
